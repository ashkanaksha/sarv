# Builds presentation/media from the source folders. Re-run after adding files.
import os, glob, json, shutil, subprocess, sys
from PIL import Image, ImageOps
import imageio_ffmpeg
Image.MAX_IMAGE_PIXELS = None
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "presentation", "media")
FF = imageio_ffmpeg.get_ffmpeg_exe()

WORLDS = [
  ("music",       ["موسیقی"]),
  ("uni",         ["دانشگاه", "تئاتر"]),
  ("sculpture",   ["مجسمه سازی"]),
  ("argo",        ["آرگو"]),
  ("factory",     ["ایرانمال هفت و هشت"]),
  ("eureka",      ["یوریکا"]),
  ("bysarv",      ["پرسونال برند bysarv"]),
  ("pedar",       ["کار برای پدر"]),
  ("phase2",      ["فاز 2 کارگاه"]),
  ("competition", ["مسابقه معماری"]),
  ("qaraylou",    ["قرایلو استودیو"]),
  ("radikal",     ["رادیکال بتن"]),
]
IMG = (".jpg", ".jpeg", ".png")
manifest = {}
for wid, dirs in WORLDS:
    d_img = os.path.join(OUT, wid); os.makedirs(os.path.join(d_img, "thumb"), exist_ok=True)
    items = []; n = 0
    for d in dirs:
        files = sorted(glob.glob(os.path.join(ROOT, d, "**", "*"), recursive=True))
        for f in files:
            ext = os.path.splitext(f)[1].lower()
            if ext in IMG:
                n += 1; name = f"{n:02d}.jpg"
                dst = os.path.join(d_img, name); th = os.path.join(d_img, "thumb", name)
                if not os.path.exists(dst):
                    im = Image.open(f); im.draft("RGB", (2400, 2400)); im = ImageOps.exif_transpose(im)
                    if im.mode in ("RGBA", "LA", "P"):
                        im = im.convert("RGBA"); bg = Image.new("RGB", im.size, (245, 245, 243)); bg.paste(im, mask=im.split()[-1]); im = bg
                    im = im.convert("RGB")
                    big = im.copy(); big.thumbnail((1920, 1920), Image.LANCZOS); big.save(dst, quality=84, optimize=True, progressive=True)
                    sm = im.copy(); sm.thumbnail((520, 520), Image.LANCZOS); sm.save(th, quality=80)
                w, h = Image.open(dst).size
                items.append({"type": "image", "src": f"media/{wid}/{name}", "thumb": f"media/{wid}/thumb/{name}", "w": w, "h": h})
            elif ext == ".mp4":
                n += 1; name = f"{n:02d}.mp4"; dst = os.path.join(d_img, name); poster = os.path.join(d_img, "thumb", f"{n:02d}.jpg")
                if not os.path.exists(dst):
                    if os.path.getsize(f) > 40e6:   # heavy file -> 1080p web encode
                        subprocess.run([FF, "-v", "error", "-y", "-i", f, "-c:v", "libx264", "-crf", "24", "-preset", "medium",
                                        "-vf", "scale='min(1920,iw)':-2", "-c:a", "aac", "-b:a", "160k", "-movflags", "+faststart", dst], check=True)
                    else:
                        shutil.copyfile(f, dst)
                if not os.path.exists(poster):
                    subprocess.run([FF, "-v", "error", "-y", "-ss", "2", "-i", dst, "-frames:v", "1", "-vf", "scale=520:-2", poster], check=True)
                w, h = Image.open(poster).size
                items.append({"type": "video", "src": f"media/{wid}/{name}", "thumb": f"media/{wid}/thumb/{n:02d}.jpg", "w": w, "h": h})
    manifest[wid] = items
    # remove outputs whose source was deleted
    keep = {os.path.basename(it["src"]) for it in items} | {os.path.basename(it["thumb"]) for it in items}
    for f in os.listdir(d_img):
        if f != "thumb" and f not in keep: os.remove(os.path.join(d_img, f))
    for f in os.listdir(os.path.join(d_img, "thumb")):
        if f not in keep: os.remove(os.path.join(d_img, "thumb", f))
    print(wid, len(items))

# intro soundtrack (swap media/audio/intro.mp3 for a piano track any time)
os.makedirs(os.path.join(OUT, "audio"), exist_ok=True)
aud = os.path.join(OUT, "audio", "intro.mp3")
if not os.path.exists(aud):
    subprocess.run([FF, "-v", "error", "-y", "-i", os.path.join(ROOT, "موسیقی", "هراتی.mp4"), "-vn",
                    "-af", "afade=t=in:d=4", "-c:a", "libmp3lame", "-q:a", "3", aud], check=True)

# logo: crop + white-on-transparent PNG
lg = Image.open(os.path.join(ROOT, "logo sarv.png")).convert("RGBA")
lg = lg.crop(lg.getbbox()); lg.thumbnail((900, 900), Image.LANCZOS)
pad = Image.new("RGBA", (lg.width + 80, lg.height + 80), (0, 0, 0, 0)); pad.paste(lg, (40, 40))
pad.save(os.path.join(OUT, "logo.png"))

with open(os.path.join(OUT, "manifest.js"), "w", encoding="utf-8") as fh:
    fh.write("// generated by tools/prep_media.py\nexport const MEDIA = " + json.dumps(manifest, ensure_ascii=False, indent=1) + ";\n")
print("done")
